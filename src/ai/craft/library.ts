const BY_ID = new Map(CRAFT_CARDS.map((card) => [card.id, card]));

/** A card by topic id or label. */
export function craftCard(topic: string): CraftCard | undefined {
  const key = topic.trim();
  return BY_ID.get(key) ?? CRAFT_CARDS.find((card) => card.label === key);
}

export function craftCardText(card: CraftCard): string {
  return [
    `【${card.label}】${card.core}`,
    `做法：\n${card.moves.map((move) => `- ${move}`).join("\n")}`,
    `自查：\n${card.checks.map((check) => `- ${check}`).join("\n")}`,
    `何时不用／别当成规则：\n${card.limits.map((limit) => `- ${limit}`).join("\n")}`,
    card.tensions?.length ? `相反的意见：\n${card.tensions.map((tension) => `- ${tension}`).join("\n")}` : "",
    `出处：${card.sources.join("、")}`,
  ].filter(Boolean).join("\n");
}

function bigrams(text: string): Set<string> {
  const chars = [...text.replace(/[\s，。、！？“”"'：:；;（）()]/g, "")];
  const grams = new Set<string>();
  for (let index = 0; index < chars.length - 1; index += 1) grams.add(chars[index] + chars[index + 1]);
  return grams;
}

/** Cards whose symptoms or label resemble the author's description, best first. */
export function matchCraftCards(query: string, limit = 2): CraftCard[] {
  const asked = bigrams(query);
  if (!asked.size) return [];
  const score = (phrase: string) => {
    const grams = bigrams(phrase);
    if (!grams.size) return 0;
    let shared = 0;
    for (const gram of grams) if (asked.has(gram)) shared += 1;
    return shared / grams.size;
  };
  return CRAFT_CARDS
    .map((card) => ({ card, score: Math.max(score(card.label), ...card.symptoms.map(score)) }))
    .filter((item) => item.score >= 0.5)
    .sort((left, right) => right.score - left.score)
    .slice(0, limit)
    .map((item) => item.card);
}
